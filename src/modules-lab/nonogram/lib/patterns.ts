export function patternById(id: string): PixelPattern | undefined {
  return PATTERNS.find((x) => x.id === id)
}

/** 把图案字符串转成布尔数组 */
export function patternToGrid(pattern: PixelPattern): { cols: number; rows: number; filled: boolean[] } {
  const rows = pattern.rows.length
  const cols = pattern.rows[0].length
  const filled: boolean[] = []
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) filled.push(pattern.rows[r][c] === '#')
  }
  return { cols, rows, filled }
}